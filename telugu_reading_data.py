def get_passage(language: str, difficulty: str) -> Dict[str, Any]:
    """Retrieve passage dictionary for given language and difficulty level."""
    lang = language if language in PASSAGES_CATALOG else "Telugu"
    diff = difficulty if difficulty in PASSAGES_CATALOG[lang] else "Intermediate"
    return PASSAGES_CATALOG[lang][diff]

def get_student_by_id(student_id: str) -> Dict[str, Any]:
    """Retrieve student profile by student_id."""
    for s in STUDENT_PROFILES:
        if s["student_id"] == student_id:
            return s
    return STUDENT_PROFILES[0]

